<#
.SYNOPSIS
    Generates Copilot and Cursor adapters from shared agents and host settings.
.DESCRIPTION
    Behavior stays in .ai/roles/ and shared policy; outputs require explicit reads.
    CheckOnly detects drift without writes. Orphans are reported, never deleted.
    Unmarked collisions are never overwritten except known Copilot profiles on
    explicit first adoption. Run from any directory; paths resolve from this script.
.EXAMPLE
    pwsh -NoProfile -File scripts/sync-agent-profiles.ps1 -CheckOnly
.EXAMPLE
    pwsh -NoProfile -File scripts/sync-agent-profiles.ps1
#>
param(
    [switch]$CheckOnly,
    [switch]$AdoptExistingCopilot
)

$ErrorActionPreference = 'Stop'
$repoRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
$marker = '<!-- generated by scripts/sync-agent-profiles.ps1; edit canonical sources, not this file -->'

function Read-Source([string]$RelativePath) {
    $path = [IO.Path]::GetFullPath((Join-Path $repoRoot $RelativePath))
    if (-not $path.StartsWith($repoRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Source path escapes repository: $RelativePath"
    }
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw "Missing source: $RelativePath" }
    return ([IO.File]::ReadAllText($path) -replace "`r`n", "`n")
}

function Quote-Yaml([string]$Value) {
    if ($Value -match '[\r\n]') { throw 'Multiline YAML scalar is not supported.' }
    return "'" + $Value.Replace("'", "''") + "'"
}

try {
    $registry = (Read-Source '.ai/agents.json') | ConvertFrom-Json
    $copilot = (Read-Source '.ai/adapters/copilot.json') | ConvertFrom-Json
    $cursor = (Read-Source '.ai/adapters/cursor.json') | ConvertFrom-Json
    $copilotModels = (Read-Source '.ai/adapters/copilot-models.json') | ConvertFrom-Json
    $cursorModels = (Read-Source '.ai/adapters/cursor-models.json') | ConvertFrom-Json
    foreach ($source in @($registry, $copilot, $cursor, $cursorModels)) {
        if ($source.schemaVersion -ne 1) { throw 'Unsupported or missing schemaVersion.' }
    }
    $agents = @{}
    foreach ($agent in $registry.agents) {
        if ($agent.id -notmatch '^[a-z]+(?:-[a-z]+)*$' -or $agents.ContainsKey($agent.id)) {
            throw "Invalid or duplicate logical agent ID: $($agent.id)"
        }
        if ($agent.role -notmatch '^\.ai/roles/[a-z-]+\.md$' -or [string]::IsNullOrWhiteSpace($agent.description)) {
            throw "Invalid role reference or description for $($agent.id)"
        }
        $null = Read-Source $agent.role
        $agents[$agent.id] = $agent
    }
    if (-not $agents.ContainsKey('coordinator')) { throw 'Registry must define Coordinator.' }
    $outputs = [ordered]@{}
    $sources = @('AGENTS.md', '.ai/agents.json', '.ai/WORKFLOW.md', '.ai/MODEL_ASSIGNMENTS.md',
        '.ai/TOKEN_POLICY.md', '.ai/DEFINITION_OF_DONE.md', '.ai/adapters/copilot.json',
        '.ai/adapters/copilot-models.json', '.ai/adapters/cursor.json', '.ai/adapters/cursor-models.json',
        '.ai/adapters/CURSOR.md', $cursor.entrySource)
    $sources += @($registry.agents | ForEach-Object { $_.role })
    # Current project criteria also invalidate adapters; accumulated eval history does not.
    $projectRoot = Join-Path $repoRoot '.ai/project'
    if (Test-Path -LiteralPath $projectRoot -PathType Container) {
        $sources += @(Get-ChildItem -LiteralPath $projectRoot -File -Filter '*.md' |
            Where-Object { $_.Name -ne 'EVALS_LOG.md' } |
            ForEach-Object { '.ai/project/' + $_.Name })
    }
    if ($cursor.instructionDirectory -ne '.github/instructions') { throw 'Unsupported instructionDirectory.' }
    $instructions = @(Get-ChildItem -LiteralPath (Join-Path $repoRoot $cursor.instructionDirectory) -Filter '*.instructions.md' -File | Sort-Object Name)
    $sources += @($instructions | ForEach-Object { '.github/instructions/' + $_.Name })
    # Windows PowerShell and PowerShell 7 use different culture sorting engines.
    # Order paths ordinally so the same checkout has the same fingerprint in both.
    [string[]]$sourcePaths = @($sources | Select-Object -Unique)
    [Array]::Sort($sourcePaths, [StringComparer]::Ordinal)
    $fingerprintText = (($sourcePaths | ForEach-Object { $_ + "`n" + (Read-Source $_) }) -join "`n")
    $sha = [Security.Cryptography.SHA256]::Create()
    try {
        $fingerprint = ([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($fingerprintText)))).Replace('-', '').ToLowerInvariant()
    } finally { $sha.Dispose() }
    $banner = "$marker`n<!-- shared configuration SHA256: $fingerprint -->"
    # Delegates get their role text inline plus this contract, so they do not
    # need to read kit-wide documents before every run.
    $delegateContract = @(
        '## Delegate contract',
        '',
        '- Work only within the brief from the parent Coordinator. Do not contact the user or start another agent.',
        '- Before editing or advising, read `.ai/project/ALWAYS_ON_GUARDRAILS.md` when present, the `.github/instructions/` files matching the paths in scope, and a project skill only when its trigger matches. Read other kit files only when the brief names them.',
        '- Stop and hand back when the work exceeds the brief, needs a different task weight, or touches a high-impact trigger the brief does not authorize. Say what caused the stop.',
        '- Report the outcome; files changed or inspected; checks as exact commands with exit codes and counts, or "not run"; and open issues or risks.',
        '- Never claim that a check, model, or role ran without evidence.'
    ) -join "`n"

    foreach ($hostName in @('copilot', 'cursor')) {
        $adapter = if ($hostName -eq 'copilot') { $copilot } else { $cursor }
        $models = if ($hostName -eq 'copilot') { $copilotModels } else { $cursorModels }
        $ids = @{}
        $names = @{}
        foreach ($profile in $adapter.profiles) {
            if ($profile.id -notmatch '^[a-z]+(?:-[a-z]+)*$' -or $ids.ContainsKey($profile.id)) { throw "Invalid/duplicate $hostName profile ID." }
            $ids[$profile.id] = $true
            if (-not $agents.ContainsKey($profile.agent)) { throw "Unknown logical agent: $($profile.agent)" }
            $agent = $agents[$profile.agent]
            $name = if ($hostName -eq 'copilot') { $profile.name } else { $profile.id }
            if ([string]::IsNullOrWhiteSpace($name) -or $names.ContainsKey($name)) { throw "Missing/duplicate $hostName profile name." }
            $names[$name] = $true
            $modelProperty = $models.profiles.PSObject.Properties[$name]
            if (-not $modelProperty) { throw "Missing $hostName model mapping for $name" }
            if ($hostName -eq 'copilot') {
                $tierProperty = $models.tiers.PSObject.Properties[[string]$modelProperty.Value]
                if (-not $tierProperty) { throw "Unknown Copilot model tier for $name" }
                $modelValues = @($tierProperty.Value)
                if ($modelValues.Count -eq 0) { throw "Empty Copilot model tier for $name" }
                $modelYaml = if ($modelValues.Count -eq 1) { Quote-Yaml $modelValues[0] } else {
                    '[' + (($modelValues | ForEach-Object { Quote-Yaml $_ }) -join ', ') + ']'
                }
                $tools = @($profile.tools)
                $allowedTools = switch ($profile.agent) {
                    'coordinator' { @('agent', 'read', 'search') }
                    'verifier' { @('read', 'search', 'execute') }
                    { $_ -in @('implementer', 'implementer-light', 'utility') } { @('edit', 'read', 'search') }
                    default { @('read', 'search') }
                }
                if (($tools -join ',') -cne ($allowedTools -join ',')) { throw "Unexpected Copilot tools for $name" }
                $frontMatter = @('---', "name: $name", ('description: ' + (Quote-Yaml $agent.description)),
                    'include-custom-instructions: true', "model: $modelYaml", ('tools: ' + (ConvertTo-Json -InputObject $tools -Compress)))
                if ($profile.agent -eq 'coordinator') {
                    $children = @($copilot.profiles | Where-Object { $_.agent -ne 'coordinator' } | ForEach-Object { $_.name })
                    $frontMatter += 'agents: ' + (ConvertTo-Json -InputObject $children -Compress)
                } else { $frontMatter += 'user-invocable: false' }
                $relativePath = ".github/agents/$($profile.id).agent.md"
                $hostInstruction = if ($profile.agent -eq 'coordinator') {
                    'Use the Copilot routing, family-pairing and enforced tool boundaries in .ai/MODEL_ASSIGNMENTS.md. The Coordinator profile is read-only; delegate edits and commands to its permitted specialists.'
                } else {
                    'Your tools are limited to the tools list of this profile; report to the Coordinator when the brief needs another capability.'
                }
            } else {
                if ($profile.agent -eq 'coordinator') { throw 'Cursor Coordinator must be the parent, not a specialist.' }
                if ($modelProperty.Value -isnot [string] -or [string]::IsNullOrWhiteSpace($modelProperty.Value)) { throw "Cursor model must be a single ID or inherit: $name" }
                if ($profile.readonly -isnot [bool]) { throw "Missing Cursor readonly setting for $name" }
                $expectedReadonly = $profile.agent -in @('architect', 'po-bm', 'reviewer')
                if ($profile.readonly -ne $expectedReadonly) { throw "Unexpected Cursor readonly setting for $name" }
                $frontMatter = @('---', "name: $name", ('description: ' + (Quote-Yaml $agent.description)),
                    ('model: ' + (Quote-Yaml $modelProperty.Value)), ('readonly: ' + $profile.readonly.ToString().ToLowerInvariant()), 'is_background: false')
                $relativePath = ".cursor/agents/$($profile.id).md"
                $hostInstruction = if ($profile.readonly) {
                    'Cursor enforces this profile as read-only.'
                } elseif ($profile.agent -eq 'verifier') {
                    'You may create normal build and test outputs. Never edit source, tests, configuration, or generated source; this rule is behavioral, not enforced.'
                } else {
                    'Do not run builds, tests, or other commands; the parent sequences verification. Writable permission does not authorize commands or scope expansion.'
                }
            }
            $frontMatter += '---'
            $roleLink = '[' + $profile.agent + ' role](../../' + $agent.role + ')'
            if ($profile.agent -eq 'coordinator') {
                $body = "$banner`n`nExplicitly read [AGENTS.md](../../AGENTS.md), $roleLink, [shared workflow](../../.ai/WORKFLOW.md), and [model policy](../../.ai/MODEL_ASSIGNMENTS.md) before acting. Load current project guardrails, matching path instructions and relevant skills for the delegated scope.`n`n$hostInstruction`n"
            } else {
                $roleText = (Read-Source $agent.role).Trim()
                $body = "$banner`n`n$roleText`n`n$delegateContract`n`n$hostInstruction`n`nGenerated from the $roleLink and the shared delegate contract; edit those sources, not this file.`n"
            }
            $outputs[$relativePath] = ($frontMatter -join "`n") + "`n`n" + $body
        }
        foreach ($property in $models.profiles.PSObject.Properties) {
            if (-not $names.ContainsKey($property.Name)) { throw "Orphaned $hostName model mapping: $($property.Name)" }
        }
        $mappedAgents = @($adapter.profiles | ForEach-Object { $_.agent })
        foreach ($logicalId in $agents.Keys) {
            if ($hostName -eq 'cursor' -and $logicalId -eq 'coordinator') { continue }
            if ($logicalId -notin $mappedAgents) { throw "Logical agent $logicalId has no $hostName profile." }
        }
    }

    $entry = (Read-Source $cursor.entrySource).TrimEnd("`n")
    $outputs['.cursor/rules/agent-kit.mdc'] = "---`ndescription: Shared agent-kit entry and synchronization policy`nalwaysApply: true`n---`n`n$banner`n`n$entry`n"
    foreach ($instruction in $instructions) {
        $sourcePath = '.github/instructions/' + $instruction.Name
        $content = Read-Source $sourcePath
        $match = [regex]::Match($content, '(?s)\A---\n(.*?)\n---')
        if (-not $match.Success) { throw "Instruction has no frontmatter: $sourcePath" }
        $applyTo = [regex]::Match($match.Groups[1].Value, '(?m)^applyTo:\s*(.+?)\s*$')
        if (-not $applyTo.Success) { throw "Instruction has no applyTo: $sourcePath" }
        $globs = $applyTo.Groups[1].Value.Trim().Trim('"', "'")
        if ([string]::IsNullOrWhiteSpace($globs)) { throw "Instruction has empty applyTo: $sourcePath" }
        $id = $instruction.Name -replace '\.instructions\.md$', ''
        if ($id -notmatch '^[a-z-]+$' -or $id -eq 'agent-kit') { throw "Unsupported instruction filename: $($instruction.Name)" }
        $outputs[".cursor/rules/$id.mdc"] = "---`nglobs: $(Quote-Yaml $globs)`nalwaysApply: false`n---`n`n$banner`n`nBefore working on matching files, explicitly read [$id guidance](../../$sourcePath). This is the canonical instruction shared with Copilot; its contents are not automatically inlined by this reference.`n"
    }

    # Validate ownership before any writes; never overwrite another custom profile.
    $problems = @()
    foreach ($relativePath in $outputs.Keys) {
        $path = Join-Path $repoRoot $relativePath
        if (Test-Path -LiteralPath $path -PathType Leaf) {
            $current = [IO.File]::ReadAllText($path)
            $adopt = $AdoptExistingCopilot -and $relativePath.StartsWith('.github/agents/')
            if (-not $current.Contains($marker) -and -not $adopt) { $problems += "Unmanaged collision: $relativePath (left untouched)." }
        }
    }
    foreach ($directory in @('.github/agents', '.cursor/agents', '.cursor/rules')) {
        $path = Join-Path $repoRoot $directory
        if (-not (Test-Path -LiteralPath $path -PathType Container)) { continue }
        foreach ($file in Get-ChildItem -LiteralPath $path -File) {
            $relativePath = "$directory/$($file.Name)"
            if ([IO.File]::ReadAllText($file.FullName).Contains($marker) -and -not $outputs.Contains($relativePath)) {
                $problems += "Obsolete generated file: $relativePath. Review and remove deliberately; no files deleted."
            }
        }
    }
    if ($problems.Count) { throw ($problems -join "`n") }

    $drift = @()
    foreach ($relativePath in $outputs.Keys) {
        $path = Join-Path $repoRoot $relativePath
        $current = if (Test-Path -LiteralPath $path -PathType Leaf) { [IO.File]::ReadAllText($path) -replace "`r`n", "`n" } else { $null }
        if ($current -ceq $outputs[$relativePath]) { continue }
        $drift += $relativePath
        if (-not $CheckOnly) {
            $parent = Split-Path -Parent $path
            [IO.Directory]::CreateDirectory($parent) | Out-Null
            [IO.File]::WriteAllText($path, $outputs[$relativePath], [Text.UTF8Encoding]::new($false))
            Write-Host "Synced $relativePath"
        }
    }
    if ($CheckOnly -and $drift.Count) { throw ('Adapter drift: ' + ($drift -join ', ') + '. Run scripts/sync-agent-profiles.ps1.') }
    Write-Host "Both host adapters match the shared registry and policy ($($outputs.Count) managed files; $($drift.Count) updated)."
    exit 0
} catch {
    Write-Error $_ -ErrorAction Continue
    exit 1
}
